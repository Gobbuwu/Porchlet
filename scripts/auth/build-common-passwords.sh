#!/usr/bin/env bash
# Rebuilds src/lib/auth/common-passwords.ts (ADR 0019). Source: the NCSC's top 100,000 passwords
# from Have I Been Pwned, as copied into SecLists (MIT licence), pinned to one commit and checked
# by SHA-256. Keeps the entries Porchlet's password rules would accept (10 to 72 characters),
# lower-cased and in list order, so the check covers at least the top 3,000 (ASVS 5.0.0 6.2.4).
set -euo pipefail
commit=fcde9140df969b1e4d7bb056122646dace4ed4cc
url="https://raw.githubusercontent.com/danielmiessler/SecLists/$commit/Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt"
want=c2e5696882c603b76bb67a47ee970897e5a76fc4c3f5547abe3d0ca340c576e0
out=src/lib/auth/common-passwords.ts
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
curl -fsSL "$url" -o "$tmp"
echo "$want  $tmp" | sha256sum -c --quiet
node - "$tmp" "$commit" >"$out" <<'JS'
const [file, commit] = process.argv.slice(2);
const seen = new Set();
for (const line of require("node:fs").readFileSync(file, "utf8").split(/\r?\n/)) {
  const length = [...line].length;
  if (length >= 10 && length <= 72) seen.add(line.toLowerCase());
}
console.log("// Generated by scripts/auth/build-common-passwords.sh; don't edit by hand (ADR 0019).");
console.log(`// Source: NCSC top 100k passwords via SecLists (MIT), commit ${commit}.`);
console.log("// Entries of 10 to 72 characters, lower-cased, most common first.");
console.log("export const COMMON_PASSWORDS: readonly string[] = [");
for (const pw of seen) console.log(`  ${JSON.stringify(pw)},`);
console.log("];");
JS
echo "wrote $out: $(($(wc -l <"$out") - 5)) passwords"
